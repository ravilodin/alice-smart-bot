def alice_response(text):
    return jsonify({
        "version": "1.0",
        "response": {
            "text": text,
            "tts": text,
            "end_session": False
        }
    })


# =========================================================
# WEBHOOK
# =========================================================

@app.route("/webhook", methods=["POST"])
def webhook():

    data = request.get_json(
        force=True,
        silent=True
    ) or {}

    req = data.get(
        "request",
        {}
    )

    text = (
        req.get("command")
        or ""
    ).strip()

    session_data = data.get(
        "session",
        {}
    )

    session_id = (
        session_data.get("session_id")
        or session_data.get("application_id")
        or "default"
    )

    is_new_session = (
        session_data.get("new") is True
        or req.get("type") == "SessionNew"
    )

    # -----------------------------------------------------
    # НОВАЯ СЕССИЯ
    # -----------------------------------------------------

    if is_new_session:

        sessions[session_id] = []

        return alice_response(
            "Ассаламу алейкум, братишка. Уцышка на связи."
        )

    # -----------------------------------------------------
    # ПУСТОЙ ЗАПРОС
    # -----------------------------------------------------

    if not text:

        return alice_response(
            "Эй, брат, ты чё хотел спросить?"
        )

    # -----------------------------------------------------
    # ПРОВЕРКА КЛЮЧА
    # -----------------------------------------------------

    if not YANDEX_API_KEY:

        return alice_response(
            "Брат, сервер не настроен. "
            "Нет YANDEX_API_KEY."
        )

    # -----------------------------------------------------
    # СОЗДАЁМ ИЛИ ПОЛУЧАЕМ ИСТОРИЮ
    # -----------------------------------------------------

    if session_id not in sessions:
        sessions[session_id] = []

    history = sessions[session_id]

    # Сохраняем сообщение пользователя
    history.append({
        "role": "user",
        "content": text
    })

    # Не даём памяти бесконечно разрастаться.
    # Оставляем последние 20 сообщений.
    history = history[-20:]

    sessions[session_id] = history

    # -----------------------------------------------------
    # ЗАПРОС К YANDEXGPT
    # -----------------------------------------------------

    try:

        messages = [
            {
                "role": "system",
                "content": SYSTEM_PROMPT
            }
        ]

        messages.extend(history)

        response = client.chat.completions.create(
            model=MODEL_NAME,
            messages=messages,
            temperature=0.9,
            max_tokens=300
        )

        answer = (
            response
            .choices[0]
            .message
            .content
            .strip()
        )

        if not answer:
            answer = "Брат, я чё-то завис."

        # Сохраняем ответ Уцышки
        history.append({
            "role": "assistant",
            "content": answer
        })

        sessions[session_id] = history[-20:]

        return alice_response(answer)

    except Exception as error:

        print(
            "YANDEX API ERROR:",
            repr(error)
        )

        return alice_response(
            "Брат, я сейчас заглючил. "
            "Секунду, ща разберёмся."
        )


